-- Esquema base da E1 (Stack, seção 6). Migrations só adicionam estruturas (ver README).
-- Campos exigidos para enviar à curadoria (RN-02, RN-03) ficam anuláveis em cenario_versao porque
-- um rascunho pode estar incompleto: essa validação é da entidade de domínio.

-- ---------------------------------------------------------------------------------------------
-- Acesso
-- ---------------------------------------------------------------------------------------------

CREATE TABLE usuario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          TEXT        NOT NULL,
    email         TEXT        NOT NULL,
    senha_hash    TEXT        NOT NULL,
    ativo         BOOLEAN     NOT NULL DEFAULT TRUE,
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX uq_usuario_email ON usuario (lower(email));

CREATE TABLE usuario_perfil (
    usuario_id BIGINT      NOT NULL REFERENCES usuario (id),
    perfil     TEXT        NOT NULL CHECK (perfil IN ('PROFESSOR', 'CURADOR', 'ADMINISTRADOR')),
    criado_em  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (usuario_id, perfil)
);

-- RN-32: a turma é identificada só por estes campos; não existe lista de estudantes.
CREATE TABLE turma (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escola        TEXT        NOT NULL,
    ano_serie     TEXT        NOT NULL,
    turno         TEXT        NOT NULL,
    rotulo        TEXT        NOT NULL,
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_turma UNIQUE (escola, ano_serie, turno, rotulo)
);

CREATE TABLE parametro (
    chave         TEXT PRIMARY KEY,
    valor         TEXT        NOT NULL,
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------------------------
-- Cenários
-- ---------------------------------------------------------------------------------------------

-- O ano é texto porque há habilidades de vários anos (EF15LP01 vale do 1º ao 5º).
CREATE TABLE habilidade_bncc (
    codigo     TEXT PRIMARY KEY,
    descricao  TEXT        NOT NULL,
    etapa      TEXT        NOT NULL,
    ano        TEXT        NOT NULL,
    componente TEXT        NOT NULL,
    criado_em  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE cenario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    autor_id      BIGINT      NOT NULL REFERENCES usuario (id),
    status        TEXT        NOT NULL DEFAULT 'RASCUNHO'
                  CHECK (status IN ('RASCUNHO', 'EM_CURADORIA', 'APROVADO', 'SUSPENSO', 'ARQUIVADO')),
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX ix_cenario_autor ON cenario (autor_id);
CREATE INDEX ix_cenario_status ON cenario (status);

-- O status da versão é separado do status do cenário porque, ao editar um cenário aprovado, a nova
-- versão fica em rascunho enquanto a versão vigente continua valendo em sala (RN-08).
CREATE TABLE cenario_versao (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cenario_id             BIGINT      NOT NULL REFERENCES cenario (id),
    numero                 INTEGER     NOT NULL CHECK (numero > 0),
    status                 TEXT        NOT NULL DEFAULT 'RASCUNHO'
                           CHECK (status IN ('RASCUNHO', 'EM_CURADORIA', 'APROVADA')),
    titulo                 TEXT        NOT NULL,
    conteudo               JSONB       NOT NULL,
    componente             TEXT,
    etapa                  TEXT,
    ano                    TEXT,
    faixa_etaria           TEXT,
    duracao_prevista_min   INTEGER     CHECK (duracao_prevista_min BETWEEN 10 AND 30),
    criado_por_id          BIGINT      NOT NULL REFERENCES usuario (id),
    criado_em              TIMESTAMPTZ NOT NULL DEFAULT now(),
    aprovado_por_id        BIGINT      REFERENCES usuario (id),
    aprovado_em            TIMESTAMPTZ,
    CONSTRAINT uq_cenario_versao_numero UNIQUE (cenario_id, numero),
    CONSTRAINT ck_cenario_versao_aprovacao
        CHECK (status <> 'APROVADA' OR (aprovado_por_id IS NOT NULL AND aprovado_em IS NOT NULL))
);

CREATE INDEX ix_cenario_versao_filtros ON cenario_versao (componente, ano);

-- A FK fica fora do CREATE TABLE porque cenario e cenario_versao se referenciam.
ALTER TABLE cenario
    ADD COLUMN versao_vigente_id BIGINT REFERENCES cenario_versao (id);

CREATE FUNCTION impede_alterar_versao_aprovada() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'A versão aprovada % é imutável (RN-08)', OLD.id
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_cenario_versao_imutavel
    BEFORE UPDATE OR DELETE ON cenario_versao
    FOR EACH ROW
    WHEN (OLD.status = 'APROVADA')
    EXECUTE FUNCTION impede_alterar_versao_aprovada();

CREATE TABLE versao_habilidade (
    cenario_versao_id BIGINT      NOT NULL REFERENCES cenario_versao (id),
    habilidade_codigo TEXT        NOT NULL REFERENCES habilidade_bncc (codigo),
    criado_em         TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (cenario_versao_id, habilidade_codigo)
);

CREATE INDEX ix_versao_habilidade_codigo ON versao_habilidade (habilidade_codigo);

CREATE TABLE devolucao (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cenario_versao_id BIGINT      NOT NULL REFERENCES cenario_versao (id),
    curador_id        BIGINT      NOT NULL REFERENCES usuario (id),
    comentario        TEXT        NOT NULL CHECK (btrim(comentario) <> ''),
    criado_em         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX ix_devolucao_versao ON devolucao (cenario_versao_id);

-- ---------------------------------------------------------------------------------------------
-- Adaptador de IA
-- ---------------------------------------------------------------------------------------------

-- Não referencia mensagem, porque o módulo ia não depende de sessoes: é a mensagem que aponta para
-- estes metadados. Assim, eles sobrevivem à exclusão das conversas (RN-33).
CREATE TABLE resposta_ia_meta (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provedor       TEXT        NOT NULL,
    modelo         TEXT        NOT NULL,
    parametros     JSONB       NOT NULL DEFAULT '{}',
    versao_prompt  TEXT        NOT NULL,
    tokens_entrada INTEGER     CHECK (tokens_entrada >= 0),
    tokens_saida   INTEGER     CHECK (tokens_saida >= 0),
    custo          NUMERIC(12, 6) CHECK (custo >= 0),
    latencia_ms    INTEGER     CHECK (latencia_ms >= 0),
    criado_em      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------------------------
-- Sessões
-- ---------------------------------------------------------------------------------------------

CREATE TABLE sessao (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id        BIGINT      NOT NULL REFERENCES usuario (id),
    turma_id            BIGINT      NOT NULL REFERENCES turma (id),
    cenario_versao_id   BIGINT      NOT NULL REFERENCES cenario_versao (id),
    tipo                TEXT        NOT NULL DEFAULT 'SIMULACAO'
                        CHECK (tipo IN ('SIMULACAO', 'CONTROLE')),
    status              TEXT        NOT NULL DEFAULT 'EM_ANDAMENTO'
                        CHECK (status IN ('EM_ANDAMENTO', 'PAUSADA', 'ENCERRADA')),
    motivo_pausa        TEXT
                        CHECK (motivo_pausa IN ('MANUAL', 'CONTEUDO_BLOQUEADO', 'LIMITE_50_MINUTOS', 'CENARIO_SUSPENSO')),
    presentes           INTEGER     CHECK (presentes >= 0),
    engajamento         SMALLINT    CHECK (engajamento BETWEEN 1 AND 5),
    perguntas_turma     INTEGER     CHECK (perguntas_turma >= 0),
    respostas_ia        INTEGER     CHECK (respostas_ia >= 0),
    duracao_efetiva_seg INTEGER     CHECK (duracao_efetiva_seg >= 0),
    tempo_pausa_seg     INTEGER     CHECK (tempo_pausa_seg >= 0),
    iniciada_em         TIMESTAMPTZ NOT NULL DEFAULT now(),
    encerrada_em        TIMESTAMPTZ,
    criado_em           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_sessao_motivo_pausa CHECK ((status = 'PAUSADA') = (motivo_pausa IS NOT NULL)),
    CONSTRAINT ck_sessao_encerramento CHECK ((status = 'ENCERRADA') = (encerrada_em IS NOT NULL))
);

-- RN-10: cada turma tem no máximo uma sessão em andamento.
CREATE UNIQUE INDEX uq_sessao_em_andamento_por_turma ON sessao (turma_id) WHERE status = 'EM_ANDAMENTO';
CREATE INDEX ix_sessao_professor ON sessao (professor_id);
CREATE INDEX ix_sessao_turma ON sessao (turma_id);
CREATE INDEX ix_sessao_versao ON sessao (cenario_versao_id);

CREATE TABLE evento_sessao (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sessao_id   BIGINT      NOT NULL REFERENCES sessao (id),
    tipo        TEXT        NOT NULL CHECK (tipo IN ('PAUSA', 'RETOMADA', 'REINICIO')),
    motivo      TEXT        CHECK (motivo IN ('MANUAL', 'CONTEUDO_BLOQUEADO', 'LIMITE_50_MINUTOS', 'CENARIO_SUSPENSO')),
    ocorrido_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    criado_em   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_evento_sessao_motivo CHECK (tipo <> 'PAUSA' OR motivo IS NOT NULL)
);

CREATE INDEX ix_evento_sessao_sessao ON evento_sessao (sessao_id, ocorrido_em);

-- RN-11: a autoria é genérica; nenhuma coluna identifica estudantes.
CREATE TABLE mensagem (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sessao_id           BIGINT      NOT NULL REFERENCES sessao (id),
    autoria             TEXT        NOT NULL CHECK (autoria IN ('TURMA', 'IA')),
    texto               TEXT        NOT NULL,
    resposta_ia_meta_id BIGINT      UNIQUE REFERENCES resposta_ia_meta (id),
    criado_em           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_mensagem_meta_so_da_ia CHECK (autoria = 'IA' OR resposta_ia_meta_id IS NULL)
);

CREATE INDEX ix_mensagem_sessao ON mensagem (sessao_id, criado_em);
-- O job de retenção (RN-33) seleciona as mensagens por data.
CREATE INDEX ix_mensagem_criado_em ON mensagem (criado_em);

-- ---------------------------------------------------------------------------------------------
-- Auditoria
-- ---------------------------------------------------------------------------------------------

-- O hash é anulável porque o encadeamento é opcional (Stack, seção 6).
CREATE TABLE log_auditoria (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT      NOT NULL REFERENCES usuario (id),
    acao        TEXT        NOT NULL,
    entidade    TEXT        NOT NULL,
    entidade_id TEXT,
    detalhes    JSONB       NOT NULL DEFAULT '{}',
    hash        TEXT,
    ocorrido_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX ix_log_auditoria_ocorrido_em ON log_auditoria (ocorrido_em);
CREATE INDEX ix_log_auditoria_usuario ON log_auditoria (usuario_id);

-- RN-35: o trigger vale para qualquer usuário do banco, ao contrário de uma permissão revogada.
CREATE FUNCTION impede_alterar_log_auditoria() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'O log de auditoria não pode ser alterado nem apagado (RN-35)'
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_log_auditoria_imutavel
    BEFORE UPDATE OR DELETE ON log_auditoria
    FOR EACH ROW
    EXECUTE FUNCTION impede_alterar_log_auditoria();

CREATE TRIGGER tg_log_auditoria_sem_truncate
    BEFORE TRUNCATE ON log_auditoria
    FOR EACH STATEMENT
    EXECUTE FUNCTION impede_alterar_log_auditoria();
